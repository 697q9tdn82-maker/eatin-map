const TAG_COLORS = {
  "データ追加": ["#e3f2fd", "#0077b6"],
  "新機能": ["#ffeaea", "#e63946"],
  "改善": ["#e8f5e9", "#2d6a4f"],
  "お知らせ": ["#f0f0f0", "#555"],
};
export function tagStyle(tag) {
  const [bg, color] = TAG_COLORS[tag] || TAG_COLORS["お知らせ"];
  return { fontSize: "10.5px", fontWeight: 800, background: bg, color, borderRadius: 20, padding: "2px 8px", whiteSpace: "nowrap" };
}

// "2026-11-12" → "2026年11月12日"
export function newsDate(d) {
  const [y, m, day] = d.split("-").map(Number);
  return `${y}年${m}月${day}日`;
}
