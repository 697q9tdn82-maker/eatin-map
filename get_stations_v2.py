def get_coords(name):
    url = "https://msearch.gsi.go.jp/address-search/AddressSearch?q=" + urllib.parse.quote(name + "駅")
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
        with urllib.request.urlopen(req, timeout=5) as res:
            data = json.loads(res.read())
            if data:
                coords = data[0]["geometry"]["coordinates"]
                return round(coords[1], 6), round(coords[0], 6)
    except:
        pass
    return None, None

results = {}
failed = []
unique_stations = list(dict.fromkeys(stations))
print(f"取得開始：{len(unique_stations)}駅")

for i, name in enumerate(unique_stations):
    lat, lng = get_coords(name)
    if lat:
        results[name] = {"lat": lat, "lng": lng}
        print(f"✓ ({i+1}/{len(unique_stations)}) {name}: {lat:.4f}, {lng:.4f}")
    else:
        failed.append(name)
        print(f"✗ ({i+1}/{len(unique_stations)}) {name}: 取得失敗")
    time.sleep(0.3)

js = "const NEW_STATION_COORDS = {\n"
for name, coords in sorted(results.items()):
    js += f'  "{name}": {{ lat: {coords["lat"]}, lng: {coords["lng"]} }},\n'
js += "};"

with open("new_station_coords.js", "w", encoding="utf-8") as f:
    f.write(js)

print(f"\n完了！取得成功: {len(results)}駅 / 失敗: {len(failed)}駅")
print(f"new_station_coords.js に保存しました")
